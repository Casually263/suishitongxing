import { test, expect } from '@playwright/test'

const username = `e2e_${Date.now()}`
const password = 'Browser-test-password-2026'
test('real registration, login, saved profile, reload, sign out and route guard', async ({ page }) => {
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await page.goto('/register')
  await page.locator('input[name="username"]').fill(username)
  await page.locator('input[name="email"]').fill(`${username}@example.test`)
  await page.locator('input[name="password"]').fill(password)
  await page.locator('input[name="confirmPassword"]').fill(password)
  await page.locator('input[name="adultConfirmed"]').check()
  await page.locator('input[name="acceptedTerms"]').check()
  const registration = page.waitForResponse(response => response.url().endsWith('/api/portal/auth/register') && response.request().method() === 'POST')
  await page.locator('button[type="submit"]').click()
  expect((await registration).status()).toBe(201)
  await expect(page).toHaveURL(/\/login$/)
  await page.locator('input[name="identifier"]').fill(username)
  await page.locator('input[name="password"]').fill(password)
  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('heading', { name: new RegExp(username) })).toBeVisible()
  await page.screenshot({ path: '../docs/testing/phase-1-home.png', fullPage: true })
  await page.goto('/profile')
  await page.locator('input[name="displayName"]').fill('春日同行者')
  await page.locator('input[name="country"]').fill('中国')
  const save = page.waitForResponse(response => response.url().endsWith('/api/portal/profile') && response.request().method() === 'PUT')
  await page.locator('button[type="submit"]').click()
  expect((await save).status()).toBe(200)
  await page.reload()
  await expect(page.locator('input[name="displayName"]')).toHaveValue('春日同行者')
  await page.screenshot({ path: '../docs/testing/phase-1-profile.png', fullPage: true })
  const firstTab = await page.context().newPage()
  const secondTab = await page.context().newPage()
  await Promise.all([firstTab.goto('/profile'), secondTab.goto('/profile')])
  await expect(firstTab.locator('input[name="displayName"]')).toHaveValue('春日同行者')
  await expect(secondTab.locator('input[name="displayName"]')).toHaveValue('春日同行者')
  await firstTab.close()
  await secondTab.close()
  const storage = await page.evaluate(() => JSON.stringify(localStorage))
  expect(storage).not.toContain('accessToken')
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/profile')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  expect(failures).toEqual([])
})

test('admin sign in uses real permission-protected user list and database count', async ({ page }) => {
  const adminPassword = process.env.ADMIN_PASSWORD
  test.skip(!adminPassword, 'Set ADMIN_PASSWORD from the local environment; no embedded administrator password.')
  await page.goto('/admin/login')
  await page.locator('input[name="identifier"]').fill(process.env.ADMIN_USERNAME || 'demo_admin')
  await page.locator('input[name="password"]').fill(adminPassword!)
  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/\/admin$/)
  await expect(page.getByTestId('registered-users')).toHaveText(/^[1-9][0-9]*$/)
  const listing = page.waitForResponse(response => response.url().includes('/api/admin/users?') && response.request().method() === 'GET')
  await page.goto('/admin/users')
  const firstUsername = (await (await listing).json()).data.items[0].username as string
  await expect(page.locator('table')).toContainText(firstUsername)
  await page.screenshot({ path: '../docs/testing/phase-1-admin-users.png', fullPage: true })
  await page.reload()
  await expect(page.locator('table')).toContainText(firstUsername)
  await page.getByRole('button', { name: '退出登录' }).click()
  await expect(page).toHaveURL(/\/admin\/login$/)
})

test('bilingual login stays readable on a narrow screen with no horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/login')
  await page.getByRole('button', { name: 'Switch language' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  const sizes = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }))
  expect(sizes.content).toBeLessThanOrEqual(sizes.viewport)
  await page.screenshot({ path: '../docs/testing/phase-1-login-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Switch language' }).click()
  await page.screenshot({ path: '../docs/testing/phase-1-login-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto('/register')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360)
})
