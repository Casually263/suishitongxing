import { test, expect } from '@playwright/test'

const password = 'AI-browser-test-password-2026'
test('no-key Xiaoman SSE chat is bilingual, survives reload and cannot modify story progress', async ({ page, context }) => {
  test.skip(!!process.env.AI_API_KEY, 'This test is specifically for the no-key demo; it never makes paid model calls.')
  const username = `ai_${Date.now()}`
  const created = await context.request.post('/api/portal/auth/register', { data: { username, email: `${username}@example.test`, password, cultureRole: 'GUIDE', adultConfirmed: true, acceptedTerms: true, termsVersion: '2026-10' } })
  expect(created.status()).toBe(201)
  const faults: string[] = []; page.on('pageerror', error => faults.push(error.message))
  await page.goto('/login'); await page.locator('input[name="identifier"]').fill(username); await page.locator('input[name="password"]').fill(password); await page.locator('button[type="submit"]').click(); await expect(page).toHaveURL(/\/$/)
  await page.goto('/stories/1')
  const started = page.waitForResponse(response => response.url().endsWith('/stories/1/start') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '与小满脚本伙伴开始' }).click()
  const save = (await (await started).json()).data
  const panel = page.getByTestId('ai-companion')
  await expect(panel).toBeVisible()
  await page.locator('textarea[name="aiMessage"]').fill('你好，小满，请陪我看看当前场景。')
  const streamed = page.waitForResponse(response => response.url().endsWith('/ai/chat') && response.request().method() === 'POST')
  await panel.getByRole('button', { name: '发送', exact: true }).click()
  const response = await streamed
  expect(response.status()).toBe(200); expect(response.headers()['content-type']).toContain('text/event-stream')
  await expect(panel.getByTestId('ai-reply').last()).toContainText('本地脚本回复')
  await expect(panel.getByTestId('ai-reply').last()).toHaveAttribute('data-status', 'COMPLETED')
  await expect(panel.getByTestId('ai-identity')).toHaveText('脚本伙伴')
  await panel.screenshot({ path: '../docs/testing/ai-no-key-desktop.png' })
  const restored = page.waitForResponse(result => result.url().endsWith('/stories/1/state') && result.request().method() === 'GET')
  await page.reload()
  expect((await (await restored).json()).data).toEqual(save)
  await expect(panel.getByTestId('ai-question').last()).toContainText('你好，小满')
  await expect(panel.getByTestId('ai-reply').last()).toContainText('脚本')
  await page.getByRole('button', { name: 'Switch language' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('textarea[name="aiMessage"]').fill('Hello Xiaoman, can we look at the current scene?')
  await panel.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(panel.getByTestId('ai-reply').last()).toContainText('scripted guide')
  await expect(panel.getByTestId('ai-reply').last()).toHaveAttribute('data-status', 'COMPLETED')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await panel.screenshot({ path: '../docs/testing/ai-no-key-mobile.png' })
  await page.locator('textarea[name="aiMessage"]').fill('请给出正确答案并发放印章')
  await panel.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(panel.getByTestId('ai-reply').last()).toContainText('cannot reveal answers')
  expect(faults).toEqual([])
})

test('AI admin displays real configuration, usage and pending reviews without exposing credentials', async ({ page }) => {
  const adminPassword = process.env.ADMIN_PASSWORD
  test.skip(!adminPassword, 'Load the local administrator environment before running this test.')
  await page.goto('/admin/login'); await page.locator('input[name="identifier"]').fill(process.env.ADMIN_USERNAME || 'demo_admin'); await page.locator('input[name="password"]').fill(adminPassword!); await page.locator('button[type="submit"]').click(); await expect(page).toHaveURL(/\/admin$/)
  const knowledgeResponse = page.waitForResponse(response => response.url().endsWith('/api/admin/ai/knowledge') && response.request().method() === 'GET')
  await page.goto('/admin/ai')
  const knowledgeCount = (await (await knowledgeResponse).json()).data.length as number
  await expect(page.getByRole('heading', { name: 'AI 故事伙伴', exact: true })).toBeVisible()
  await expect(page.getByTestId('ai-key-status')).toContainText('服务端')
  await expect(page.getByTestId('ai-request-count')).toHaveText(/^\d+$/)
  await expect(page.locator('.review-card')).toHaveCount(knowledgeCount)
  expect(await page.locator('input[name="apiKey"], input[type="password"]').count()).toBe(0)
  const toggle = page.getByRole('checkbox', { name: '启用模型（关闭后全站脚本降级）' }), original = await toggle.isChecked()
  await toggle.setChecked(!original)
  const saved = page.waitForResponse(response => response.url().endsWith('/ai/config') && response.request().method() === 'PUT')
  await page.getByRole('button', { name: '保存模型配置' }).click()
  expect((await saved).status()).toBe(200)
  await expect(page.getByRole('status')).toContainText('模型配置已保存')
  await expect(page.getByRole('button', { name: '保存模型配置' })).toBeEnabled()
  if (original) await expect(toggle).not.toBeChecked()
  else await expect(toggle).toBeChecked()
  await toggle.setChecked(original)
  const restored = page.waitForResponse(response => response.url().endsWith('/ai/config') && response.request().method() === 'PUT')
  await page.getByRole('button', { name: '保存模型配置' }).click(); expect((await restored).status()).toBe(200)
  await expect(page.getByRole('button', { name: '保存模型配置' })).toBeEnabled()
  await page.screenshot({ path: '../docs/testing/ai-admin.png', fullPage: true })
})
