import { test, expect, type BrowserContext, type Page } from '@playwright/test'

const password = 'Story-browser-password-2026'
async function account(context: BrowserContext, role: 'GUIDE' | 'PARTNER') {
  const username = `story_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`
  const result = await context.request.post('/api/portal/auth/register', { data: { username, email: `${username}@example.test`, password, cultureRole: role, adultConfirmed: true, acceptedTerms: true, termsVersion: '2026-10' } })
  expect(result.status()).toBe(201)
  return username
}
async function login(page: Page, username: string) {
  await page.goto('/login')
  await page.locator('input[name="identifier"]').fill(username)
  await page.locator('input[name="password"]').fill(password)
  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/stories/1')
}
async function toDual(page: Page, route = 'learn') {
  await expect(page.getByTestId('story-node-title')).toHaveText('一封未写完的春信')
  await page.getByRole('button', { name: '继续故事' }).click()
  await page.getByTestId(`option-${route}`).click()
  await page.getByRole('button', { name: '继续故事' }).click()
  await page.getByTestId('option-solar').click()
  await expect(page.getByTestId('story-node-title')).toHaveText('一盘菜，两半线索')
}

