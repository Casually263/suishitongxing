test('two real browser accounts receive different clues and resume a waiting collaboration', async ({ browser, baseURL }) => {
  const aContext = await browser.newContext({ baseURL }), bContext = await browser.newContext({ baseURL })
  try {
    const a = await aContext.newPage(), b = await bContext.newPage()
    await login(a, await account(aContext, 'GUIDE'))
    await a.getByRole('button', { name: '发起真人双视角邀请' }).click()
    const code = (await a.locator('.story-invitation code').innerText()).trim()
    await login(b, await account(bContext, 'PARTNER'))
    await b.locator('input[name="inviteCode"]').fill(code)
    await b.getByRole('button', { name: '接受并开始' }).click()
    await toDual(a, 'learn'); await toDual(b, 'observe')
    await expect(a.locator('.dual-panel')).toContainText('菜单残页')
    await expect(a.getByTestId('answer-renewal')).toHaveCount(0)
    await expect(b.locator('.dual-panel')).toContainText('笺注')
    await expect(b.getByTestId('answer-five_pungent')).toHaveCount(0)
    await a.goto('/collaboration')
    await expect(a.locator('.dual-panel')).toContainText('菜单残页')
    await expect(a.getByTestId('answer-renewal')).toHaveCount(0)
    await a.getByTestId('answer-five_pungent').click()
    await expect(a.getByTestId('dual-status')).toHaveText('已提交，等待另一位伙伴。')
    await a.reload()
    await expect(a.getByTestId('dual-status')).toHaveText('已提交，等待另一位伙伴。')
    await a.setViewportSize({ width: 1440, height: 1000 })
    await a.screenshot({ path: '../docs/testing/ui-collaboration-desktop.png', fullPage: true, animations: 'disabled' })
    await a.setViewportSize({ width: 390, height: 844 })
    expect(await a.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
    await a.screenshot({ path: '../docs/testing/ui-collaboration-mobile.png', fullPage: true, animations: 'disabled' })
    await a.goto('/stories/1')
    await expect(a.getByTestId('dual-status')).toHaveText('已提交，等待另一位伙伴。')
    await b.getByTestId('answer-renewal').click()
    await expect(b.getByTestId('story-node-title')).toHaveText('答案之外的一句话')
    await expect(a.getByTestId('story-node-title')).toHaveText('答案之外的一句话', { timeout: 12000 })
    await expect(a.locator('.story-feedback')).toContainText('+15')
    await b.reload()
    await expect(b.getByTestId('story-node-title')).toHaveText('答案之外的一句话')
  } finally { await aContext.close(); await bContext.close() }
})
